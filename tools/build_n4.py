# Builds www/js/n4.js from n4.csv, kanji.json and hi4.txt. Usage: python3 build_n4.py <tools dir> <out file>
import csv,json,sys
src=sys.argv[1]
rows=list(csv.DictReader(open(src+'/n4.csv',encoding='utf8')))
txt=open(src+'/hi4.txt',encoding='utf8').read().strip().split('\nKANJI\n')
lines=txt[0].split('\n'); hi=[]
for i,l in enumerate(lines):
    e=l.split(';'); exp=10 if i<len(lines)-1 else len(rows)-10*(len(lines)-1)
    assert len(e)==exp,(i,len(e),exp,l); hi+=e
assert len(hi)==len(rows)
EN={61:'next time; this time',408:'for the sake of; because of',453:'she; girlfriend',76:'so; that way',384:'quite; not easily',255:'certain; if I remember correctly'}
first=lambda s:s.split(';')[0].strip()
def en(i,m):
    if i in EN: return EN[i]
    m=m.strip().replace('-- ','')
    if len(m)>42: m=m[:42].rsplit(',',1)[0] if ',' in m[:42] else m[:42].rsplit(' ',1)[0]
    return m.rstrip(',;( ')
W=[[first(r['expression']),first(r['reading']),en(i,r['meaning']),hi[i],i%22+1] for i,r in enumerate(rows)]
d=json.load(open(src+'/kanji.json',encoding='utf8'))
ks=sorted([c for c,v in d.items() if v.get('jlpt_new')==4],key=lambda c:d[c]['freq'] or 9999)
kh=txt[1].strip().split(';'); assert len(kh)==len(ks),(len(kh),len(ks))
K=[[c,(d[c]['readings_on'] or [''])[0],(d[c]['readings_kun'] or [''])[0],(d[c].get('wk_meanings') or d[c]['meanings'])[0].lstrip('^'),kh[i],i*22//len(ks)+1] for i,c in enumerate(ks)]
open(sys.argv[2],'w',encoding='utf8').write('// Generated by build_n4.py. Words: open-anki-jlpt-decks (MIT). Kanji: davidluzgouveia/kanji-data (MIT). Hindi: Mikomi.\nexport const N4W = '+json.dumps(W,ensure_ascii=False,separators=(',',':'))+';\nexport const N4K = '+json.dumps(K,ensure_ascii=False,separators=(',',':'))+';\n')
print(len(W),len(K),W[207],W[490],W[667],K[0],K[165])
