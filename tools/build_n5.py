import csv,json,sys
src=sys.argv[1]
rows=list(csv.DictReader(open(src+'/n5.csv',encoding='utf8')))
txt=open(src+'/hi.txt',encoding='utf8').read().strip().split('\nKANJI\n')
lines=txt[0].split('\n'); hi=[]
for i,l in enumerate(lines):
    e=l.split(';'); exp=10 if i<len(lines)-1 else len(rows)-10*(len(lines)-1)
    assert len(e)==exp,(i,len(e),exp); hi+=e
assert len(hi)==len(rows),(len(hi),len(rows))
EN={24:'thick',34:'sweet',219:'mouth',470:'bird',236:'fine; no, thank you',55:'painful',68:'unpleasant',325:'person from (a country)',411:'first day of the month',57:'one day',378:'tall; expensive',713:'I (formal)',714:'I'}
first=lambda s:s.split(';')[0].strip()
def en(i,m):
    if i in EN: return EN[i]
    m=m.strip(); 
    if len(m)>42: m=m[:42].rsplit(',',1)[0].rsplit(' ',1)[0] if ',' in m[:42] else m[:42].rsplit(' ',1)[0]
    return m.rstrip(',;( ')
cats={}
for i,h in enumerate(hi): cats.setdefault(h[0],[]).append(i)
score={}
for c,ix in cats.items():
    for r,i in enumerate(ix): score[i]=(r/len(ix))*(0.45 if c=='a' else 1)
CORE='私 これ それ あれ この その あの ここ そこ あそこ 何 誰 どこ はい いいえ 人 学生 先生 友達 名前 本 水 今 今日 明日 行く 来る 食べる 飲む 見る する 大きい 小さい いい; よい 好き 有る'.split(' ')
CORE=[c.replace('いい;','いい; よい') for c in CORE if c!='よい']
seenc=set()
for i,r in enumerate(rows):
    e=r['expression']
    if e in CORE and e not in seenc and i!=713: seenc.add(e); score[i]=-1+CORE.index(e)/100
order=sorted(range(len(rows)),key=lambda i:(score[i],i))
per=-(-len(rows)//20); unit={i:k//per+1 for k,i in enumerate(order)}
W=[[first(rows[i]['expression']),first(rows[i]['reading']),en(i,rows[i]['meaning']),hi[i][1:],unit[i]] for i in order]
d=json.load(open(src+'/kanji.json',encoding='utf8'))
ks=sorted([c for c,v in d.items() if v.get('jlpt_new')==5],key=lambda c:d[c]['freq'] or 9999)
kh=txt[1].strip().split(';'); assert len(kh)==len(ks),(len(kh),len(ks))
K=[[c,(d[c]['readings_on'] or [''])[0],(d[c]['readings_kun'] or [''])[0],(d[c].get('wk_meanings') or d[c]['meanings'])[0].lstrip('^'),kh[i],i//4+1] for i,c in enumerate(ks)]
open(sys.argv[2],'w',encoding='utf8').write('// Generated by build_n5.py. Words: open-anki-jlpt-decks (MIT). Kanji: davidluzgouveia/kanji-data (MIT). Hindi: Mikomi.\n// word: [japanese, reading, english, hindi, unit]   kanji: [kanji, on, kun, english, hindi, unit]\nexport const N5W = '+json.dumps(W,ensure_ascii=False,separators=(',',':'))+';\nexport const N5K = '+json.dumps(K,ensure_ascii=False,separators=(',',':'))+';\n')
print(len(W),len(K),'per unit',per); print(W[:3],W[400],K[:2]); print(sorted(set(c for c in cats)),[sum(1 for w in W if w[4]==u) for u in (1,20)])
